alter table public.tenant_audit_log enable row level security;

drop policy if exists tenants_read_members on public.tenants;
create policy tenants_read_members on public.tenants
for select to authenticated
using (public.is_tenant_member(id));

drop policy if exists profiles_read_same_tenant on public.profiles;
create policy profiles_read_same_tenant on public.profiles
for select to authenticated
using (
  id=auth.uid() or exists(
    select 1
    from public.tenant_memberships mine
    join public.tenant_memberships theirs on theirs.tenant_id=mine.tenant_id
    where mine.user_id=auth.uid() and mine.active=true and theirs.user_id=profiles.id and theirs.active=true
  )
);

drop policy if exists memberships_read_same_tenant on public.tenant_memberships;
create policy memberships_read_same_tenant on public.tenant_memberships
for select to authenticated
using (public.is_tenant_member(tenant_id));

drop policy if exists connectors_admin_only on public.connector_credentials;
create policy connectors_admin_only on public.connector_credentials
for select to authenticated
using (public.is_tenant_admin(tenant_id));

drop policy if exists autotrade_read_member on public.autotrade_configs;
create policy autotrade_read_member on public.autotrade_configs
for select to authenticated
using (public.is_tenant_member(tenant_id));

drop policy if exists intents_read_member on public.execution_intents;
create policy intents_read_member on public.execution_intents
for select to authenticated
using (public.is_tenant_member(tenant_id));

drop policy if exists audit_read_admin on public.tenant_audit_log;
create policy audit_read_admin on public.tenant_audit_log
for select to authenticated
using (public.is_tenant_admin(tenant_id));

create or replace function public.handle_new_user_profile()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,display_name)
  values(new.id,coalesce(new.raw_user_meta_data->>'display_name',split_part(new.email,'@',1)))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute function public.handle_new_user_profile();
